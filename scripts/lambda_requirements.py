"""Generate or verify Lambda runtime requirements from the tested uv lockfiles."""
import argparse
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGES = ("agent", "api")


def exported_requirements(package_dir: Path) -> str:
    """Export the entire runtime closure, including the AWS SDK, with hashes."""
    result = subprocess.run(
        ["uv", "export", "--locked", "--offline", "--no-dev", "--no-emit-local",
         "--no-annotate", "--no-header"],
        cwd=package_dir, check=True, capture_output=True, text=True, timeout=60,
    )
    header = (
        f"# Generated from {package_dir.name}/uv.lock by scripts/lambda_requirements.py.\n"
        "# Regenerate after updating the lockfile; do not edit this file manually.\n"
        "# Includes the AWS SDK so Lambda uses the same versions as CI.\n"
    )
    return header + result.stdout.strip() + "\n"


def update_requirements(package_dir: Path, *, check: bool) -> bool:
    expected = exported_requirements(package_dir)
    path = package_dir / "requirements-lambda.txt"
    if check:
        matches = path.exists() and path.read_text(encoding="utf-8") == expected
        print(f"{package_dir.name}: {'matches lockfile' if matches else 'runtime requirements are stale'}")
        return matches
    path.write_text(expected, encoding="utf-8")
    print(f"{package_dir.name}: generated runtime requirements")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    parser.add_argument("--package", choices=PACKAGES, help="check one package; default is both")
    args = parser.parse_args()
    packages = (args.package,) if args.package else PACKAGES
    success = True
    for package in packages:
        success = update_requirements(ROOT / package, check=args.check) and success
    if not success:
        print("Run python scripts/lambda_requirements.py from the repository root.")
    return 0 if success else 1


if __name__ == "__main__":
    raise SystemExit(main())
